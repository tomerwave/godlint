use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

use crate::{glob, paths};

const HEADER_LINES: usize = 10;
const BYTE_ORDER_MARK: char = '\u{feff}';
const COMMENT_LEADERS: [&str; 4] = ["//", "/*", "*", "#"];
const HEADER_MARKERS: [&str; 2] = ["@generated", "DO NOT EDIT"];
const PULUMI_MARKER: &str = "*** warning: this file was generated by";
const ATTRIBUTES_FILE: &str = ".gitattributes";
const MACRO_DEFINITION: &str = "[attr]";
const LINGUIST_VALUE: &str = "linguist-generated=";

pub(crate) struct Attributes {
    by_directory: BTreeMap<PathBuf, Vec<Assignment>>,
}

struct Assignment {
    pattern: String,
    generated: bool,
}

pub(crate) fn declares_generated(contents: &str) -> bool {
    contents
        .trim_start_matches(BYTE_ORDER_MARK)
        .lines()
        .take(HEADER_LINES)
        .any(marks_generated)
}

fn marks_generated(line: &str) -> bool {
    let line = line.trim_start();

    COMMENT_LEADERS
        .iter()
        .any(|leader| line.starts_with(leader))
        && (HEADER_MARKERS.iter().any(|marker| line.contains(marker))
            || line.to_lowercase().contains(PULUMI_MARKER))
}

impl Attributes {
    pub(crate) fn read(root: &Path, files: &[PathBuf]) -> Self {
        let mut by_directory = BTreeMap::new();

        for directory in files
            .iter()
            .filter_map(|file| file.strip_prefix(root).ok())
            .flat_map(|relative| relative.ancestors().skip(1))
        {
            by_directory
                .entry(directory.to_path_buf())
                .or_insert_with(|| read_assignments(&root.join(directory).join(ATTRIBUTES_FILE)));
        }

        Self { by_directory }
    }

    pub(crate) fn marks_generated(&self, relative: &Path) -> bool {
        let directories: Vec<&Path> = relative.ancestors().skip(1).collect();

        directories
            .into_iter()
            .rev()
            .filter_map(|directory| Some((directory, self.by_directory.get(directory)?)))
            .flat_map(|(directory, assignments)| {
                let within = within(relative, directory);

                assignments
                    .iter()
                    .filter(move |assignment| assignment.matches(&within))
            })
            .last()
            .is_some_and(|assignment| assignment.generated)
    }
}

fn within(relative: &Path, directory: &Path) -> String {
    let inner = relative.strip_prefix(directory).unwrap_or(relative);

    paths::slashed(&inner.to_string_lossy()).into_owned()
}

fn read_assignments(path: &Path) -> Vec<Assignment> {
    if paths::is_symlink(path) {
        return Vec::new();
    }

    fs::read_to_string(path)
        .map(|text| text.lines().filter_map(assignment).collect())
        .unwrap_or_default()
}

fn assignment(line: &str) -> Option<Assignment> {
    let mut fields = line.split_whitespace();
    let pattern = fields.next().filter(|pattern| names_files(pattern))?;
    let generated = fields.filter_map(linguist_state).next_back()?;

    Some(Assignment {
        pattern: pattern.to_owned(),
        generated,
    })
}

fn names_files(pattern: &str) -> bool {
    !pattern.starts_with(['#', '"', '!'])
        && !pattern.starts_with(MACRO_DEFINITION)
        && !pattern.ends_with('/')
}

fn linguist_state(attribute: &str) -> Option<bool> {
    match attribute {
        "linguist-generated" | "linguist-generated=true" => Some(true),
        "-linguist-generated" | "!linguist-generated" => Some(false),
        _ => attribute.strip_prefix(LINGUIST_VALUE).map(|_| false),
    }
}

impl Assignment {
    fn matches(&self, within: &str) -> bool {
        if !self.pattern.contains('/') {
            let name = within.rsplit_once('/').map_or(within, |(_, name)| name);

            return glob::matches_name(&self.pattern, name);
        }

        let anchored = self.pattern.strip_prefix('/').unwrap_or(&self.pattern);

        glob::matches_path(anchored, within)
    }
}
